// Writes README.md from data/projects.json and data/live.json. The sections are
// SVG tiles from scripts/sections.mjs; every tile is its own link.
import { readFile, writeFile } from "node:fs/promises";

const live = JSON.parse(await readFile("data/live.json", "utf8"));
const projects = JSON.parse(await readFile("data/projects.json", "utf8"));
const now = JSON.parse(await readFile("data/now.json", "utf8"));
const user = live.user;
const repos = live.github.repos;

const pic = (base, alt, width) =>
  `<picture><source media="(prefers-color-scheme: dark)" srcset="assets/${base}-dark.svg"><source media="(prefers-color-scheme: light)" srcset="assets/${base}-light.svg"><img alt="${alt.replace(/"/g, "&quot;")}" src="assets/${base}-dark.svg" ${width}></picture>`;
const tile = (base, alt, href) => (href ? `<a href="${href}">${pic(base, alt, 'width="400"')}</a>` : pic(base, alt, 'width="400"'));
const pills = [...(projects.portfolio.live && projects.portfolio.url ? [{ key: "portfolio", label: "Portfolio", url: projects.portfolio.url }] : []), ...projects.pills];
const fmt = (n) => n.toLocaleString("en-US");

const products = projects.products.map((p) => tile(`v5/product-${p.shot.split(".")[0]}`, `${p.name}: ${p.status}. ${p.line}`, p.link));
const oss = projects.openSource.filter((p) => repos[p.repo]).map((p) => tile(`v5/oss-${p.repo}`, `${p.name}: ${p.line}`, `https://github.com/${user}/${p.repo}`));
const ossLinks = projects.openSource.flatMap((p) => Object.entries(p.links).map(([k, v]) => `<a href="${v}">${p.name} ${k}</a>`)).join(" · ");
const pairs = (items) => items.reduce((rows, x, i) => (i % 2 ? rows[rows.length - 1].push(x) : rows.push([x]), rows), []).map((r) => r.join("\n")).join("\n<br/>\n");
const foremind = projects.proxsoft.find((p) => p.link)?.link;

const md = `<!-- Generated by scripts/readme.mjs from data/*.json. Edit those files, not this one. -->

<div align="center">

${pic("brain", `Shagun Choudhary. I build AI agents that do real work. A rotating brain of 365 neurons, one per day of my last year on GitHub: ${fmt(live.github.total)} contributions.`, 'width="100%"')}

${pills.map((p) => `<a href="${p.url}">${pic(`v5/pill-${p.key}`, p.label, 'height="40"')}</a>`).join("\n")}

<p>${projects.intro.replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2">$1</a>')}</p>

${tile("v5/proxsoft", `At Proxsoft: ${projects.proxsoft.map((p) => `${p.name}, ${p.status}`).join("; ")}`, foremind)}
${tile("v5/now", `Now building: ${now.items.join(" ")}`)}

<br/>

${pairs(products)}

<br/>

${oss.join("\n")}

<sub>${ossLinks}</sub>

<br/>

${tile("v5/year", `${fmt(live.github.total)} contributions in the last 365 days`)}
${tile("v5/reach", "Reach: YouTube, Instagram and GitHub numbers")}

<picture>
  <source media="(prefers-color-scheme: dark)" srcset="https://raw.githubusercontent.com/${user}/${user}/output/github-snake-dark.svg" />
  <source media="(prefers-color-scheme: light)" srcset="https://raw.githubusercontent.com/${user}/${user}/output/github-snake.svg" />
  <img alt="Contribution snake" src="https://raw.githubusercontent.com/${user}/${user}/output/github-snake-dark.svg" width="100%" />
</picture>

<sub>Every picture on this page is drawn by <a href="scripts">my own generator</a> and rebuilt every day from GitHub and YouTube numbers. Last run ${live.generatedAt.slice(0, 10)}.</sub>

</div>
`;
await writeFile("README.md", md);
console.log(`README.md ${md.length} chars`);
