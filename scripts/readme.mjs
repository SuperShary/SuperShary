// Writes README.md from data/projects.json, data/now.json and data/live.json.
import { readFile, writeFile } from "node:fs/promises";

const live = JSON.parse(await readFile("data/live.json", "utf8"));
const projects = JSON.parse(await readFile("data/projects.json", "utf8"));
const now = JSON.parse(await readFile("data/now.json", "utf8"));
const user = live.user;
const repos = live.github.repos;

const pic = (base, alt, width = "100%") =>
  `<picture><source media="(prefers-color-scheme: dark)" srcset="assets/${base}-dark.svg"><source media="(prefers-color-scheme: light)" srcset="assets/${base}-light.svg"><img alt="${alt}" src="assets/${base}-dark.svg" width="${width}"></picture>`;
const badge = (label, logo, href) =>
  `<a href="${href}"><img alt="${label}" src="https://img.shields.io/badge/${encodeURIComponent(label).replace(/-/g, "--")}-0b0f14?style=for-the-badge&logo=${logo}&logoColor=22D3EE"></a>`;
const pairs = (items) => {
  const rows = [];
  for (let i = 0; i < items.length; i += 2) rows.push(items.slice(i, i + 2).join("\n"));
  return rows.join("\n<br/>\n");
};
const weekOf = new Date(now.week + "T00:00:00Z").toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });

const featured = projects.featured.filter((p) => repos[p.repo]);
const grid = featured.map((p) => {
  const href = p.links.live || p.links.site || `https://github.com/${user}/${p.repo}`;
  return `<a href="${href}">${pic(`cards/${p.repo}`, `${p.title}: ${p.hook}`, "49%")}</a>`;
});
const channels = projects.channels.map((c) => `<a href="https://www.youtube.com/@${c.handle}">${pic(`cards/yt-${c.handle}`, `${c.name} on YouTube: ${c.hook}`, "49%")}</a>`);
const privateCards = projects.private.map((p, i) => pic(`cards/private-${i}`, `${p.title}: ${p.hook}`, "49%"));

const linkRows = featured.map((p) => {
  const extra = Object.entries(p.links).map(([k, v]) => `[${k}](${v})`).join(" · ") || "·";
  return `| **${p.title}** | [${p.repo}](https://github.com/${user}/${p.repo}) | ${extra} |`;
});
const more = projects.more.filter((r) => repos[r]).map((r) => `[${r}](https://github.com/${user}/${r})`).join(" · ");

const md = `<!-- Generated by scripts/readme.mjs from data/*.json. Edit those files, not this one. -->

<div align="center">

${pic("brain", `A rotating brain of 365 neurons, one per day of my last year on GitHub. ${live.github.total} contributions; brighter neurons are busier days.`)}

${badge("SuperShary", "youtube", "https://www.youtube.com/@SuperSharyG63")}
${badge("Shagun Choudhary", "youtube", "https://www.youtube.com/@Shagunchoudharyrocks")}
${badge("LinkedIn", "linkedin", projects.socials.linkedin)}
${badge("X", "x", projects.socials.x)}
${badge("Instagram", "instagram", projects.socials.instagram)}

</div>

### ⚡ Building this week <sub>· week of ${weekOf}</sub>

${now.items.map((i) => `- ${i}`).join("\n")}

### 📊 Data profile

<div align="center">

${pic("data", `Data profile: ${live.github.total} contributions, ${live.github.streak.longest} day longest streak, languages and YouTube reach.`)}

</div>

<sub>A GitHub Action pulls every number here from the GitHub API and the public YouTube channel pages, every day. None of it is typed by hand.</sub>

**Stack:** TypeScript · Next.js · Node · Python · Swift · Electron · Fastify · SQLite · Azure · Vercel · n8n · FFmpeg · three.js

### 🧠 Projects <sub>· every card opens the project</sub>

<div align="center">

${pairs(grid)}

</div>

### 🎬 Channels

<div align="center">

${pairs(channels)}

</div>

### 🔒 In production, private code

<div align="center">

${pairs(privateCards)}

</div>

### 🔗 Every link

| Project | Code | Open |
|---|---|---|
${linkRows.join("\n")}

More public repos: ${more}

### 🌌 Activity

<div align="center">

<picture>
  <source media="(prefers-color-scheme: dark)" srcset="https://raw.githubusercontent.com/${user}/${user}/main/profile-3d-contrib/profile-night-green.svg" />
  <source media="(prefers-color-scheme: light)" srcset="https://raw.githubusercontent.com/${user}/${user}/main/profile-3d-contrib/profile-green.svg" />
  <img alt="3D contribution calendar, last year" src="https://raw.githubusercontent.com/${user}/${user}/main/profile-3d-contrib/profile-night-green.svg" width="100%" />
</picture>

<picture>
  <source media="(prefers-color-scheme: dark)" srcset="https://raw.githubusercontent.com/${user}/${user}/output/github-snake-dark.svg" />
  <source media="(prefers-color-scheme: light)" srcset="https://raw.githubusercontent.com/${user}/${user}/output/github-snake.svg" />
  <img alt="Contribution snake" src="https://raw.githubusercontent.com/${user}/${user}/output/github-snake-dark.svg" width="100%" />
</picture>

<sub>This profile rebuilds itself every day. The brain, the data card and the cards are drawn by <a href="scripts">my own generator</a> (<a href="docs/RESEARCH-v3.md">how it works</a>). Last run ${live.generatedAt.slice(0, 10)}.</sub>

</div>
`;
await writeFile("README.md", md);
console.log(`README.md ${md.length} chars, ${featured.length} project cards`);
