// Writes README.md from data/projects.json, data/now.json and data/live.json.
import { readFile, writeFile } from "node:fs/promises";

const live = JSON.parse(await readFile("data/live.json", "utf8"));
const projects = JSON.parse(await readFile("data/projects.json", "utf8"));
const now = JSON.parse(await readFile("data/now.json", "utf8"));
const user = live.user;
const repos = live.github.repos;

const pic = (base, alt) =>
  `<picture><source media="(prefers-color-scheme: dark)" srcset="assets/${base}-dark.svg"><source media="(prefers-color-scheme: light)" srcset="assets/${base}-light.svg"><img alt="${alt}" src="assets/${base}-dark.svg" width="100%"></picture>`;
const fmt = (n) => (n == null ? null : n.toLocaleString("en-US"));
const weekOf = new Date(now.week + "T00:00:00Z").toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });
const s = projects.socials;

const proxsoft = projects.proxsoft.map((p) => `- **${p.link ? `[${p.name}](${p.link})` : p.name}** · *${p.status}*<br>${p.line}`);
const products = projects.products.map((p) => `- **[${p.name}](${p.link})** · *${p.status}*<br>${p.line}`);
const openSource = projects.openSource.filter((p) => repos[p.repo]).map((p) => {
  const extra = Object.entries(p.links).map(([k, v]) => `[${k}](${v})`).join(" · ");
  const stars = repos[p.repo].stars ? ` · ★ ${repos[p.repo].stars}` : "";
  return `- **[${p.name}](https://github.com/${user}/${p.repo})**${stars} · ${extra}<br>${p.line}`;
});
const channels = projects.channels.map((c) => {
  const yt = live.youtube.find((y) => y.handle === c.handle);
  const subs = yt?.subscribers != null ? ` · ${fmt(yt.subscribers)} subscribers` : "";
  return `- **[${c.name}](https://www.youtube.com/@${c.handle})** on YouTube${subs}<br>${c.hook}`;
});
const more = projects.more.filter((r) => repos[r]).map((r) => `[${r}](https://github.com/${user}/${r})`).join(" · ");

const md = `<!-- Generated by scripts/readme.mjs from data/*.json. Edit those files, not this one. -->

<div align="center">

${pic("brain", `A rotating brain of 365 neurons, one per day of my last year on GitHub. ${fmt(live.github.total)} contributions; brighter neurons are busier days.`)}

[YouTube](${s.youtube}) · [Instagram](${s.instagram}) · [Discord](${s.discord}) · [LinkedIn](${s.linkedin}) · [X](${s.x})

</div>

${projects.intro}

### Now building <sub>· week of ${weekOf}</sub>

${now.items.map((i) => `- ${i}`).join("\n")}

### At Proxsoft

${proxsoft.join("\n")}

### My products

${products.join("\n")}

### Open source

${openSource.join("\n")}

<sub>More public repos: ${more}</sub>

### Channels

${channels.join("\n")}
- **[SuperShary AI Community](${s.discord})** on Discord<br>Questions, builds and job help.

### By the numbers

<div align="center">

${pic("data", `Data profile: ${fmt(live.github.total)} contributions in the last year, ${live.github.streak.longest} day longest streak, languages and YouTube reach.`)}

</div>

<sub>A GitHub Action pulls every number from the GitHub API and the public YouTube pages, every day. The contribution count is GitHub's own, which includes private work.</sub>

**Stack:** TypeScript · Next.js · Node · Python · Swift · Electron · Supabase · Azure · Vercel · MCP

<div align="center">

<picture>
  <source media="(prefers-color-scheme: dark)" srcset="profile-3d-contrib/profile-night-green.svg" />
  <source media="(prefers-color-scheme: light)" srcset="profile-3d-contrib/profile-green.svg" />
  <img alt="3D contribution calendar, last year" src="profile-3d-contrib/profile-night-green.svg" width="100%" />
</picture>

<picture>
  <source media="(prefers-color-scheme: dark)" srcset="https://raw.githubusercontent.com/${user}/${user}/output/github-snake-dark.svg" />
  <source media="(prefers-color-scheme: light)" srcset="https://raw.githubusercontent.com/${user}/${user}/output/github-snake.svg" />
  <img alt="Contribution snake" src="https://raw.githubusercontent.com/${user}/${user}/output/github-snake-dark.svg" width="100%" />
</picture>

<sub>This profile rebuilds itself every day. The brain and the data card are drawn by <a href="scripts">my own generator</a> (<a href="docs/RESEARCH-v3.md">how it works</a>). Last run ${live.generatedAt.slice(0, 10)}.</sub>

</div>
`;
await writeFile("README.md", md);
console.log(`README.md ${md.length} chars`);
